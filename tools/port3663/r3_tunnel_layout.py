"""Generate the shared per-build B profile from reviewed contracts, unarmed."""
from pathlib import Path
import json
import re

ROOT=Path(__file__).resolve().parents[2]
DOCS=ROOT/'docs/probe-3663'
core=json.loads((DOCS/'R2-CORE-LIST.json').read_text(encoding='utf-8'))
matches={r['row']:r for r in json.loads((DOCS/'R2-MATCHES.json').read_text(encoding='utf-8'))['rows']}
bounds=json.loads((DOCS/'port-evidence/r3/descriptor-bounds.json').read_text(encoding='utf-8'))['rows']
pump=json.loads((DOCS/'port-evidence/r3/pump-adoption.json').read_text(encoding='utf-8'))
extra=dict(bounds);extra['B065']=pump
source=(ROOT/'src/mod/session2/offsets_s2.h').read_text(encoding='utf-8')
names=set(re.findall(r'inline constexpr \w+ (\w+)',source))
rows=[r for r in core if r['tier']=='B' and r['symbol'] in names]
assert len(rows)==70 and len({r['symbol'] for r in rows})==70
header=ROOT/'src/mod/game/build_3663.h'
text=header.read_text(encoding='utf-8')
start,end='// R3 tunnel constants BEGIN','// R3 tunnel constants END'
if start in text:text=text[:text.index(start)]+text[text.index(end)+len(end):]
section=start+'\nnamespace r3_tunnel {\n'
for key,r in sorted(extra.items()):
    assert r['adopted']
    section+=f'inline constexpr uintptr_t {r["symbol"]} = {r["target"]}; // R3 {key}; 2976 {r["old"]}\n'
section+='''inline constexpr uint32_t kPacketMax = 0x7FDA; // R3 B075 native PostPacket bound
inline constexpr uint32_t kOrdinaryPayloadMax = 0x7FC1; // R3 B075 native ordinary decoder bound
inline constexpr uint32_t kDescriptorSkip = 0; // R3 B078: target visits every aligned pointer
} // namespace r3_tunnel
'''+end+'\n'
text=text.replace('}  // namespace cdmp::game::build_3663',section+'\n}  // namespace cdmp::game::build_3663')
header.write_bytes(text.encode('utf-8'))
result='''#pragma once
// Generated by tools/port3663/r3_tunnel_layout.py. Address data grants no permission.
// Legacy module behavior stays on its original values; 3663 requires compiled B.
#include <span>
#include "common/troc_frame.h"
#include "mod/game/build_guard.h"
#include "mod/session2/offsets_s2.h"
namespace cdmp::session2 {
struct TunnelLayout {
    bool target3663 = false;
    uintptr_t kImageBase = off::kImageBase;
    uint32_t kPeTimestamp = off::kPeTimestamp;
    size_t packet_max = troc::kMaxPacketSize;
    size_t ordinary_payload_max = troc::kMaxPacketSize - troc::kHeaderSize;
    uintptr_t descriptor_skip = 0x80;
    uint64_t no_epoch = 0x7FFFFFFFFFFFFFFFULL;
    uint32_t crypto_enabled_offset = 0x24;
    uint32_t packet_epoch_offset = 0x8020;
    uint16_t connect_opcode = 2319;
    uintptr_t server_framework_mode = 0x6A65564;
'''
arrays=[]
for r in rows:
    name=r['symbol'];array=bool(re.search(r'\b'+name+r'\s*\[',source))
    if array:
        arrays.append(name);result+=f'    std::span<const uint8_t> {name} = off::{name};\n'
    else:result+=f'    decltype(off::{name}) {name} = off::{name};\n'
result+='''};
inline constexpr TunnelLayout kTunnelLayout2976{};
inline constexpr TunnelLayout kTunnelLayout3663{
    .target3663 = true,
    .kImageBase = game::build_3663::kImageBase,
    .kPeTimestamp = game::build_3663::kPeTimestamp,
    .packet_max = game::build_3663::r3_tunnel::kPacketMax,
    .ordinary_payload_max = game::build_3663::r3_tunnel::kOrdinaryPayloadMax,
    .descriptor_skip = game::build_3663::r3_tunnel::kDescriptorSkip,
    .no_epoch = game::build_3663::tunnel_layout::kNoEpoch,
    .crypto_enabled_offset = game::build_3663::tunnel_layout::kNativeCryptoEnabledOffset,
    .packet_epoch_offset = game::build_3663::tunnel_layout::kNativePacketEpochOffset,
    .connect_opcode = game::build_3663::tunnel_layout::kOpConnectCryptogramToServerReq,
    .server_framework_mode = game::build_3663::core_rvas::B073_kServerFrameworkMode,
'''
for r in rows:
    key=r['r2'];name=r['symbol']
    assert matches[key]['adopted'] or key in extra,(key,name)
    if key in extra:expr='r3_tunnel::'+name
    elif r['adopted_r1']:expr=name
    elif r['kind'] in ('function/global RVA','vtable RVA'):expr='core_rvas::'+key+'_'+name
    else:expr='tunnel_layout::'+name
    result+=f'    .{name} = game::build_3663::{expr}, // {key}\n'
result+='''};
inline const TunnelLayout* tunnel_layout(const game::build_guard::ImageIdentity& id) {
    namespace g = game::build_guard;
    if (id.kind==g::IdentityKind::Supported && id.timestamp_known &&
        id.timestamp==off::kPeTimestamp && id.mapped_base==off::kImageBase) return &kTunnelLayout2976;
    if (g::select_3663_tiers(id,{true,true,false,false},
        {game::build_3663::kTierAComplete,game::build_3663::kTierBComplete,false,false}).tier_b_tunnel)
        return &kTunnelLayout3663;
    return nullptr;
}
inline std::optional<troc::PacketView> parse_tunnel_packet(std::span<const uint8_t> bytes,
        troc::Dir direction,const TunnelLayout& layout) {
    if (bytes.size()>layout.packet_max) return std::nullopt;
    auto view=troc::parse_wire(bytes,direction);
    if (!view) return std::nullopt;
    const bool internal=view->opcode==troc::kOpLogoutSessionReq ||
        view->opcode==troc::kOpLogoutSessionAck || view->opcode==troc::kOpLogoutUserAck;
    if (!internal && view->payload.size()>layout.ordinary_payload_max) return std::nullopt;
    return view;
}
inline bool core_tunnel_request_allowed(std::span<const uint8_t> bytes, const TunnelLayout& layout) {
    const auto view = parse_tunnel_packet(bytes, troc::Dir::ToHostServer, layout);
    return view && view->opcode == layout.connect_opcode && view->slot == -1;
}
} // namespace cdmp::session2
'''
(ROOT/'src/mod/session2/tunnel_layout.h').write_bytes(result.encode('utf-8'))
(ROOT/'build/r3/tunnel-profile-fields.json').write_bytes((json.dumps(dict(rows=[r['r2'] for r in rows],arrays=arrays),indent=2)+'\n').encode())
print('Generated 70-field profile, explicit target bounds and no-skip scan; B remains gated')
