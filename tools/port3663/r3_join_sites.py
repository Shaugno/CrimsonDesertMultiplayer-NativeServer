"""Build exact-byte passive field trace sites from the hashed target file.

No RVA adoption is implied. Four unique paired native bodies/callers from
R2-FIELD-SHARING and identity-contracts establish the candidate roles. Exit
sites are decoded epilogue instructions in the same .pdata functions.
"""
from pathlib import Path
import hashlib
import json
from pe_identity import PE

ROOT = Path(__file__).resolve().parents[2]
image = PE(Path(r'D:\SteamLibrary\steamapps\common\Crimson Desert\bin64\CrimsonDesert.exe'))
assert image.sha256 == '8BE67178D9B9A149C361A731051665E0BA4D441E250AE1DFE645BD6E524345C8'
sites = [
    ('AcquireField', 0x2E08520, 0x2E085AC, 5),
    ('EnterField', 0x2ECB130, 0x2ECB63B, 8),
    ('TravelTransition', 0x2ECA480, 0x2ECB113, 7),
    ('LobbyLoad', 0x2E879A0, 0x2E87A45, 8),
]
header = '''#pragma once
// Generated by r3_join_sites.py; passive candidates, never Tier C adapters.
#include <array>
#include <cstdint>
namespace cdmp::game::r3_join_probe {
struct Site { uintptr_t rva; uint8_t relocated; std::array<uint8_t,16> bytes; };
inline constexpr std::array<Site,8> kSites{{
'''
rows = []
for role, entry, exit, exit_size in sites:
    ranges = [(a,b) for a,b in image.ranges if a == entry]
    assert len(ranges) == 1 and entry < exit < ranges[0][1]
    pair = []
    for address, relocated in [(entry,5),(exit,exit_size)]:
        data = image.data[image.offset(address,16):][:16]
        header += '    {' + hex(address) + ',' + str(relocated) + ',{' + ','.join(hex(b) for b in data) + '}},\n'
        pair.append(dict(rva=hex(address),guard=data.hex(' '),relocated=relocated))
    rows.append(dict(role=role,pdata=[hex(x) for x in ranges[0]],sites=pair,
                     basis='Paired native body, unique strong candidate and reviewed caller; R3 rule 3',adopted=False))
header += '}};\n}\n'
(ROOT/'src/mod/game/r3_join_sites.h').write_bytes(header.encode('utf-8'))
proofs = []
for name in ['field-acquire-enter-target.txt','field-mover-target.txt','identity-contracts-target.txt']:
    p = ROOT/'docs/probe-3663/port-evidence/r2'/name
    proofs.append(dict(path=str(p.relative_to(ROOT)),sha256=hashlib.sha256(p.read_bytes()).hexdigest().upper()))
result = dict(exe_sha256=image.sha256,sites=rows,evidence=proofs,
    omissions=['StatusLoad, LoginMgr and AddActor are jump thunks without .pdata entries; not hooked under candidate-entry rule.',
               'Signature lead 2C171E0 belongs to 2C16F10, whose two-argument body differs from legacy Phases; not treated as C099.',
               'No passive native actor lookup, reference call, lock call or factory call; roster-wide ownership may remain unresolved.'])
(ROOT/'docs/probe-3663/port-evidence/r3/join-preflight.json').write_bytes((json.dumps(result,indent=2)+'\n').encode('utf-8'))
print('Eight exact-byte passive sites; C remains closed')
