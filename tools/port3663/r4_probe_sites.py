"""Extract exact guards at verified native instruction boundaries for R4 logging."""
from pathlib import Path
import hashlib
import json
import re
from pe_identity import PE

root=Path(__file__).resolve().parents[2]
pe=PE(r'D:\SteamLibrary\steamapps\common\Crimson Desert\bin64\CrimsonDesert.exe')
assert pe.sha256=='8BE67178D9B9A149C361A731051665E0BA4D441E250AE1DFE645BD6E524345C8'
files=['build/r4/core-context-new.txt','build/r4/identity-sites-new.txt',
       'build/r4/sam-join-new.txt','build/r4/component-context-new.txt',
       'build/r2/identity-contracts-target.txt','build/r3/phase-standard-target.txt']
instructions={}
for name in files:
    text=(root/name).read_text(encoding='utf-8-sig')
    for address,instruction in re.findall(r'^(14[0-9a-f]{7}) (.+)$',text,flags=re.M):
        instructions[int(address,16)-pe.image_base]=instruction
points=[('VecEntry',0x4CAE10),('VecExit',0x4CAF2B),('OwnerKey',0x2C5300F),
        ('LoginMgr',0x2A12A58),('ClearLobby',0x2F4AF52),('ClearList',0x2F4AF79),
        ('LobbyConstant',0x2E87DB0),('LobbyAdd',0x2E87E10),('KeyClass',0x2D741EA),
        ('SessionId',0x2A0EEC0),('MoveFlag',0x23E1106),('Component',0x2295D80),
        ('FieldLocks',0xEB6877E),('Phases',0x2C17410)]
rows=[]
for name,rva in points:
    assert rva in instructions,(name,hex(rva))
    end=next(a for a in sorted(instructions) if a>=rva+5)
    assert 5<=end-rva<=16,(name,hex(end))
    # Every relocated instruction boundary must be present in the same listing.
    body=[(a,instructions[a]) for a in sorted(instructions) if rva<=a<end]
    guard=pe.data[pe.offset(rva,16):][:16]
    rows.append(dict(name=name,rva=hex(rva),relocated=end-rva,guard=guard.hex(),instructions=body))
header='''#pragma once
// Generated by r4_probe_sites.py. Passive diagnostics only; no gameplay permission.
#include <array>
#include <cstdint>
namespace cdmp::game::r4_core_probe {
struct Site { const char* name; uintptr_t rva; uint8_t relocated; std::array<uint8_t,16> bytes; };
inline constexpr std::array<Site,14> kSites{{
'''
for row in rows:
    header+='    {"'+row['name']+'",'+row['rva']+','+str(row['relocated'])+',{'+','.join(hex(b) for b in bytes.fromhex(row['guard']))+'}},\n'
header+='}};\n}\n'
(root/'src/mod/game/r4_probe_sites.h').write_bytes(header.encode('utf-8'))
proofs=[dict(path=name,sha256=hashlib.sha256((root/name).read_bytes()).hexdigest().upper()) for name in files]
out=root/'docs/probe-3663/port-evidence/r4/probe-sites.json'
out.write_bytes((json.dumps(dict(identity=pe.sha256,sites=rows,proofs=proofs,adopted=0),indent=2)+'\n').encode('utf-8'))
print('R4 passive boundaries/guards:',len(rows),'sites; adopted=0')
